'Personal sound-effect library, stored outside the installed skill.\n\nEDITONNY_EFFECTS_LIBRARY overrides the default personal library location. Never put personal sound files inside the distributed package. Built-in effects provide one recording per name; this library offers multiple cleaned, leveled takes with provenance and license records.\n\nResolve effects by English category, category plus source name, or exact ID. Categories describe transitions, impacts, reveals, interface actions, technology, success, errors, and humor. Preserve source and license metadata.\n\nUse the import, list, sample, remove, restore, and location commands shown by --help. Import splits long files at pauses, levels each take, and assigns a category. Removal moves takes into the library trash; it does not permanently delete them. The composer resolves selected categories to individual takes.'

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_sfx  # noqa: E402

SR = make_sfx.SR
LIBRARY_ENV = "EDITONNY_EFFECTS_LIBRARY"
INDEX = "effects.json"
UP_DB = 20 * math.log10(make_sfx.SFX_CALIBRATION)     # what sfx.volume 1.0 adds in compose_final

# category -> (label, when to use, loudest 200 ms at sfx.volume 1.0 in LUFS, longest take in s)
CATEGORIES = {
    "transition": ('Transition', 'whoosh or swish for a cut, topic change, animation, or image entrance', -10.0, 2.5),
    "impact": ("Impact", 'short hit, punch, or burst for an emphatic phrase, number, or word', -10.0, 3.0),
    "reveal": ('Reveal', 'rising bass or shimmer before or during a reveal', -12.0, 6.0),
    "interface": ("Interface", 'click, tap, button, or scroll for a list item, screen, or phone', -14.0, 1.2),
    "technology": ("Technology", 'AI, laser, beeps, energy, or data for a working system, robot, or app', -13.0, 3.0),
    "success": ("Success", 'confirmation, rise, or level-up for success and achievement', -13.0, 2.5),
    "error": ("Error", 'negative feedback, failure, or horn for a mistake or warning', -13.0, 2.0),
    "humor": ("Humor", 'cartoon boing, pop, whistle, or punch for humor', -11.0, 3.0),
}
LONG_CAP = -20.0          # loudest 3 s window at sfx.volume 1.0 (the kit's ceiling for long sounds)
PEAK_MAX_DB = -1.0
MAX_PER_GROUP = 8         # takes kept per source name (ui-audio has 38 switches)

# (origin, regex on "folder/file") -> category or None (left out), first match wins
RULES = [
    ("kenney", r"footstep|spaceengine|thruster|enginecircular|slime|spacetrash|preview", None),
    ("kenney", r"confirmation|powerup|phaserup|highup|threetone(up)?|zapthreetoneup", "success"),
    ("kenney", r"interface.*error|lowdown|zapthreetonedown|phaserdown|highdown", "error"),
    ("kenney", r"explosion|impactmetal|impactpunch|impactplate|impactwood|impacttin|impactsoft|impactplank|"
               r"impactmining|impactglass|impactbell|impactgeneric", "impact"),
    ("kenney", r"door(open|close)", "transition"),
    ("kenney", r"laser|forcefield|computernoise|zap|phase|tone|pepsound|glitch|lowrandom|lowthree", "technology"),
    ("kenney", r"scratch", "humor"),
    ("kenney", r".", "interface"),
    ("sse", r"swooshes|fireball", "transition"),
    ("sse", r"rumble|magic", "reveal"),
    ("sse", r"cartoon|whistles", "humor"),
    ("sse", r"explosions", "impact"),
    ("sse", r".", "technology"),
    ("synthetic", r"whoosh|swipe", "transition"),
    ("synthetic", r"riser|swell", "reveal"),
    ("synthetic", r"boom808", "humor"),
    ("synthetic", r"boom", "impact"),
    ("synthetic", r"glitch", "technology"),
]
LICENSES = {
    "kenney": ('CC0 1.0 (public domain), Kenney (www.kenney.nl)', "https://kenney.nl/assets/category:Audio"),
    "sse": ('CC0 1.0 (public domain), SSE Library / USC Cinema on Internet Archive',
            "https://archive.org/details/SSE_Library_SWOOSHES"),
    "synthetic": ('generated by editonny-engine (helpers/generate_effects.py), first-party code', "helpers/generate_effects.py"),
}
AUDIO_EXT = {".wav", ".ogg", ".mp3", ".flac", ".aif", ".aiff", ".m4a"}


# ------------------------------------------------------------------ library

def library_dir() -> Path:
    raw = (os.environ.get(LIBRARY_ENV) or "").strip()
    return Path(raw).expanduser() if raw else Path.home() / ".editonny" / "effects"


def load_index(lib: Path | None = None) -> dict:
    lib = lib or library_dir()
    try:
        data = json.loads((lib / INDEX).read_text(encoding="utf-8"))
        return data if isinstance(data, dict) and isinstance(data.get("effects"), dict) else {"effects": {}}
    except (OSError, ValueError):
        return {"effects": {}}


def save_index(lib: Path, index: dict) -> None:
    lib.mkdir(parents=True, exist_ok=True)
    tmp = lib / (INDEX + ".tmp")
    tmp.write_text(json.dumps(index, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    tmp.replace(lib / INDEX)


def slug(text: str) -> str:
    t = unicodedata.normalize("NFD", str(text).lower())
    t = "".join(c for c in t if unicodedata.category(c) != "Mn")
    return re.sub(r"[^a-z0-9]+", "-", t).strip("-")


def category_of(name: str) -> str | None:
    s = slug(name)
    for cid, (label, _, _, _) in CATEGORIES.items():
        if s in (cid, slug(label)):
            return cid
    return None


def takes(category: str, lib: Path | None = None, index: dict | None = None) -> list[tuple[str, dict]]:
    lib = lib or library_dir()
    index = index or load_index(lib)
    return sorted((k, v) for k, v in index["effects"].items()
                  if v.get("category") == category and (lib / v["file"]).is_file())


def resolve(names, lib: Path | None = None, seed: str = "") -> dict:
    """{name: {"path", "anchor_s", "id", "takes": [...]}} for names that are a library category or take id.

    A category gets every take in a fixed shuffled order (seeded by `seed`, the edit folder): the caller hands
    them out one per event, so a category used 5 times plays 5 different takes."""
    lib = lib or library_dir()
    index = load_index(lib)
    out = {}
    for name in names:
        base, _, term = str(name).partition(":")        # "impact:boom" = impact takes whose name has "boom"
        cat = category_of(base)
        if cat:
            ts = takes(cat, lib, index)
            if term:
                ts = [kv for kv in ts if slug(term).replace("-", "") in slug(kv[1].get("name", "")).replace("-", "")]
            if not ts:
                continue
            order = sorted(ts, key=lambda kv: hashlib.sha1(f'{seed}|{kv[0]}'.encode()).hexdigest())
            out[name] = {"id": cat, "takes": [{"path": lib / v["file"], "anchor_s": float(v.get("anchor_s", 0)),
                                               "id": k} for k, v in order]}
            continue
        v = index["effects"].get(slug(name))
        if v and (lib / v["file"]).is_file():
            t = {"path": lib / v["file"], "anchor_s": float(v.get("anchor_s", 0)), "id": slug(name)}
            out[name] = {"id": slug(name), "takes": [t]}
    return out


# ------------------------------------------------------------------ cutting and leveling

def decode(path: Path) -> np.ndarray:
    """(2, n) float at 48 kHz."""
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "2", "-ar", str(SR), "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype="<f4").astype(np.float64)
    return x.reshape(-1, 2).T


def env_db(x: np.ndarray, hop: int = SR // 100) -> np.ndarray:
    m = x.mean(axis=0)
    n = len(m) // hop
    if n == 0:
        return np.full(1, -120.0)
    f = m[: n * hop].reshape(n, hop)
    return 10 * np.log10((f * f).mean(axis=1) + 1e-12)


def pieces(x: np.ndarray, max_len: float, split: bool) -> list[np.ndarray]:
    """The sounds in x: one trimmed piece, or (split) every sound between pauses of 0.25 s or more."""
    hop = SR // 100
    e = env_db(x, hop)
    top = float(np.percentile(e, 99))
    thr = max(float(np.percentile(e, 5)) + 18.0, top - 45.0)
    loud = e >= thr
    spans, k = [], 0
    gap = 25
    while k < len(loud):
        if not loud[k]:
            k += 1
            continue
        a, quiet = k, 0
        while k < len(loud) and (quiet < gap or not split):
            quiet = 0 if loud[k] else quiet + 1
            k += 1
            if not split and k >= len(loud):
                break
        b = k - quiet if split else int(np.nonzero(loud)[0][-1]) + 1
        spans.append((a, b))
        if not split:
            break
    out = []
    for a, b in spans:
        if (b - a) * hop < 0.06 * SR:
            continue
        s0 = max(0, a * hop - int(0.02 * SR))
        s1 = min(x.shape[1], b * hop + int(0.15 * SR))
        s1 = min(s1, s0 + int(max_len * SR))
        piece = x[:, s0:s1].copy()
        fade = min(int(0.03 * SR), piece.shape[1] // 4)
        if fade > 0:
            piece[:, -fade:] *= np.linspace(1, 0, fade)
            piece[:, : int(0.003 * SR)] *= np.linspace(0, 1, int(0.003 * SR))
        out.append(piece)
    return out


def level(piece: np.ndarray, target_200: float) -> tuple[np.ndarray, dict] | None:
    """Gain so the loudest 200 ms sits at target_200 at sfx.volume 1.0, the 3 s window never above LONG_CAP,
    the peak never above PEAK_MAX_DB. None for a piece that is almost silent."""
    m = make_sfx.measure(piece)
    if m["loudness_200ms_lufs"] < -60:
        return None
    gain = (target_200 - UP_DB) - m["loudness_200ms_lufs"]
    gain = min(gain, (LONG_CAP - UP_DB) - m["short_term_max_lufs"], PEAK_MAX_DB - m["peak_dbfs"])
    out = piece * (10 ** (gain / 20))
    return out, make_sfx.measure(out)


def write_wav(path: Path, x: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    make_sfx.write_wav(path, x)


def classify(origin: str, rel: str) -> str | None:
    key = slug(rel).replace("-", "")
    for org, rx, cat in RULES:
        if org == origin and re.search(rx, key, re.I):
            return cat
    return None


def group_name(rel: str) -> str:
    stem = Path(rel).stem
    stem = re.sub(r"_CH?S_USC$", "", stem)
    return re.sub(r"[_\-]?\d+$", "", stem) or stem


def import_asset(folder: Path, origin: str, category_value: str | None, license: str | None, source_value: str | None,
             lib: Path, dry: bool = False) -> dict:
    index = load_index(lib)
    have = {v.get('source_file'): k for k, v in index["effects"].items()}
    counts: dict[str, int] = {}
    groups: dict[str, int] = {}
    files = sorted(p for p in folder.rglob("*") if p.suffix.lower() in AUDIO_EXT and "_trash" not in p.parts)
    lic, src = LICENSES.get(origin, (license or "", source_value or ""))
    if license:
        lic = license
    if source_value:
        src = source_value
    skipped = 0
    for p in files:
        rel = str(p.relative_to(folder))
        cat = category_value or classify(origin, rel)
        if not cat:
            skipped += 1
            continue
        label, _, target, max_len = CATEGORIES[cat]
        g = f'{cat}|{group_name(rel)}'
        try:
            x = decode(p)
        except subprocess.CalledProcessError:
            print(f'could not open: {rel}')
            continue
        long_reel = x.shape[1] > 6 * SR
        for j, piece in enumerate(pieces(x, max_len, split=long_reel)):
            if groups.get(g, 0) >= MAX_PER_GROUP * (3 if long_reel else 1):
                break
            tag = f'{rel}#{j}'
            if tag in have:
                continue
            got = level(piece, target)
            if got is None:
                continue
            y, m = got
            n = 1 + max([int(k.rsplit("-", 1)[1]) for k in index["effects"] if k.startswith(cat + "-")] or [0])
            eid = f'{cat}-{n:03d}'
            if not dry:
                write_wav(lib / cat / f'{eid}.wav', y)
            index["effects"][eid] = {
                "category": cat, "file": f'{cat}/{eid}.wav', "name": group_name(rel),
                "anchor_s": m["anchor_s"], 'duration_s': m["duration_s"],
                "loudness_200ms_lufs": m["loudness_200ms_lufs"], "short_term_max_lufs": m["short_term_max_lufs"],
                "origin": origin, 'source_file': tag, "license": lic, 'source': src}
            have[tag] = eid
            groups[g] = groups.get(g, 0) + 1
            counts[cat] = counts.get(cat, 0) + 1
    if not dry:
        save_index(lib, index)
    return {"new": counts, "excluded": skipped}


# ------------------------------------------------------------------ commands

def cmd_list(lib: Path, category_value: str | None) -> None:
    index = load_index(lib)
    for cid, (label, when, _, _) in CATEGORIES.items():
        if category_value and cid != category_of(category_value):
            continue
        ts = takes(cid, lib, index)
        print(f'{cid:<11} {len(ts):>4} sounds; {label}: {when}')
        if category_value:
            for k, v in ts:
                print(f"   {k}  {v['duration_s']:.2f} s  {v['name']}  ({v['origin']})")


def cmd_sample(lib: Path, category_value: str, out: Path | None) -> Path:
    cat = category_of(category_value)
    if not cat:
        raise SystemExit(f"category '{category_value}' does not exist ({', '.join(CATEGORIES)})")
    ts = takes(cat, lib)
    if not ts:
        raise SystemExit(f'category {cat} is empty')
    gap = np.zeros((2, int(0.45 * SR)))
    parts, lines, t = [], [], 0.0
    for k, v in ts:
        x = make_sfx.read_audio(lib / v["file"])
        x = x if x.shape[0] == 2 else np.vstack([x[0], x[0]])
        lines.append(f"{int(t // 60):02d}:{t % 60:05.2f}  {k}  {v['name']}")
        parts += [x, gap]
        t += x.shape[1] / SR + gap.shape[1] / SR
    out = out or lib / "_samples" / f'sample_{cat}.mp3'
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="editonny-effect-sample-") as temporary:
        wav = Path(temporary) / "sample.wav"
        write_wav(wav, np.hstack(parts))
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-b:a", "192k", str(out)], check=True)
    out.with_suffix(".txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(ts)} sounds in {out} (individual timings in {out.with_suffix('.txt').name})")
    return out


def cmd_move(lib: Path, ids: list[str], back: bool) -> None:
    index = load_index(lib)
    trash = lib / "_trash"
    for eid in ids:
        v = index["effects"].get(slug(eid))
        if not v:
            print(f'{eid}: does not exist')
            continue
        src, dst = lib / v["file"], trash / v["file"]
        if back:
            src, dst = dst, src
        if src.is_file():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(src), str(dst))
        print(f"{eid}: {('restored' if back else 'in trash')}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    im = sub.add_parser("import")
    im.add_argument('directory', type=Path)
    im.add_argument("--origin", default="files", dest='origin_value')
    im.add_argument("--category", choices=list(CATEGORIES), dest='category_value')
    im.add_argument("--license", dest='license')
    im.add_argument("--source", dest='source_value')
    im.add_argument("--dry-run", action="store_true", dest='dry_run')
    ls = sub.add_parser("list")
    ls.add_argument("--category", dest='category_value')
    am = sub.add_parser("sample")
    am.add_argument("--category", required=True, dest='category_value')
    am.add_argument("-o", type=Path, dest='o')
    for nm in ("remove", "restore"):
        sub.add_parser(nm).add_argument('ids', nargs="+")
    sub.add_parser("location")
    a = ap.parse_args()
    lib = library_dir()
    if a.cmd == "import":
        if a.origin_value == "files" and not a.category_value:
            raise SystemExit("personal files require --category")
        if a.origin_value not in LICENSES and not a.license:
            raise SystemExit('provide --license; only sounds licensed for commercial use are accepted')
        r = import_asset(a.directory, a.origin_value, a.category_value, a.license, a.source_value, lib, a.dry_run)
        print("new: " + (", ".join(f'{k} {v}' for k, v in sorted(r["new"].items())) or "none") +
              f" · excluded (unsupported): {r['excluded']} files")
    elif a.cmd == "list":
        cmd_list(lib, a.category_value)
    elif a.cmd == "sample":
        cmd_sample(lib, a.category_value, a.o)
    elif a.cmd in ("remove", "restore"):
        cmd_move(lib, a.ids, a.cmd == "restore")
    elif a.cmd == "location":
        print(lib)
    return 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, 'reconfigure'):
            stream.reconfigure(encoding='utf-8', errors=stream.errors)
    sys.exit(main())
