def boxes_blur(P, blocks):
    """Boxes blur."""
    (cut, media) = ([], {})
    for (i, b) in enumerate(blocks):
        items_list = b.get('blur') or []
        if not items_list:
            continue
        (block_start, end_b) = (b['start'], min(b['end'], P.VDUR))
        for (k, c) in enumerate(items_list):
            name = f"blur {k + 1} in block {b['scene']} at {block_start:.2f} s"
            if isinstance(c, dict):
                box = c.get('box')
                a = P.time(c, 'start', after=max(0.0, block_start - 0.5))
                z = P.time(c, 'end', after=(a if a is not None else block_start) + 0.05)
            else:
                (box, a, z) = (c, None, None)
            if not isinstance(box, (list, tuple)) or len(box) != 4 or (not all((0 <= float(v) <= 1 for v in box))):
                raise BuildError(f'{name}: box must be [x, y, width, height] in video fractions from 0 to 1')
            a = block_start if a is None else a
            z = end_b if z is None else z
            if z <= a:
                raise BuildError(f'{name}: "end" ({z:.2f}) must follow "start" ({a:.2f})')
            item = ([round(float(v), 4) for v in box], round(a, 3), round(z, 3))
            if b['scene'] == 'evidence' and b.get('file'):
                media.setdefault(i, []).append(item + (isinstance(c, dict) and ('start' in c or 'end' in c),))
            else:
                cut.append(item)
    return (cut, media)

def filter_blur(boxes, vw, vh, fps=30.0):
    """Filter blur."""
    n = len(boxes)
    parts = [f'[0:v]split={n + 1}[v0]' + ''.join((f'[c{k}]' for k in range(n)))]
    for (k, (cx, a, z)) in enumerate(boxes):
        x = int(clamp(round(cx[0] * vw / 2) * 2, 0, vw - 4))
        y = int(clamp(round(cx[1] * vh / 2) * 2, 0, vh - 4))
        w = int(clamp(round(cx[2] * vw / 2) * 2, 4, vw - x))
        h = int(clamp(round(cx[3] * vh / 2) * 2, 4, vh - y))
        (sw, sh) = (max(2, w // 20), max(2, h // 20))
        sig = max(3.0, min(w, h) / 10)
        parts.append(f'[c{k}]crop={w}:{h}:{x}:{y},scale={sw}:{sh}:flags=area,scale={w}:{h}:flags=bilinear,gblur=sigma={sig:.1f}[z{k}]')
        en = '' if a is None else f":enable='between(t,{max(0.0, a - 1 / fps):.3f},{z + 1 / fps:.3f})'"
        parts.append(f'[v{k}][z{k}]overlay={x}:{y}{en}[v{k + 1}]')
    return (';'.join(parts), f'[v{n}]')

def prepare_video(P, dst, boxes):
    """Prepare video."""
    brand = os.path.join(HERE, GENERATED_DIR, 'blur.json')
    if not boxes:
        if os.path.exists(brand):
            if os.path.exists(dst):
                os.remove(dst)
            os.remove(brand)
        copy_video(P.video_src, dst)
        return
    if not os.path.exists(P.video_src):
        raise BuildError(f'cut video not found: {P.video_src}')
    done = dict(src=signature_file(P.video_src), boxes=json.loads(json.dumps(boxes)))
    try:
        with open(brand, encoding='utf-8') as f:
            previous = json.load(f)
        if os.path.exists(dst) and previous.get('src') == done['src'] and (previous.get('boxes') == done['boxes']) and (previous.get('dst') == signature_file(dst)):
            return
    except (OSError, ValueError):
        pass
    os.makedirs(os.path.dirname(brand), exist_ok=True)
    print(f'  Baking blur into the cut ({len(boxes)} box(es))...', flush=True)
    (filter, exit) = filter_blur(boxes, P.vw, P.vh, P.fps)
    tmp = dst + '.blurring.mp4'
    run_ffmpeg(['ffmpeg', '-v', 'error', '-y', '-i', P.video_src, '-filter_complex', filter, '-map', exit, '-map', '0:a?', '-c:v', 'libx264', '-crf', '16', '-preset', 'medium', '-pix_fmt', 'yuv420p', '-c:a', 'copy', '-movflags', '+faststart', tmp], 'bake blur into the cut')
    (q0, q1) = (count_frames(P.video_src), count_frames(tmp))
    if q0 and q1 and (q0 != q1):
        warn(f'blurred cut has {q1} frames; original has {q0}: check voice synchronization')
    os.replace(tmp, dst)
    done['dst'] = signature_file(dst)
    with open(brand, 'w', encoding='utf-8') as f:
        json.dump(done, f, ensure_ascii=False, indent=1)

def blur_media(b, boxes):
    """Blur media."""
    src = os.path.join(HERE, b['file'])
    if not os.path.exists(src):
        raise BuildError(f"File not found: {b['file']}. Copy it to assets/.")
    video = b['file'].lower().endswith(('.mp4', '.mov', '.webm', '.m4v'))
    (base, ext) = os.path.splitext(os.path.basename(b['file']))
    rel = os.path.join(GENERATED_DIR, f"{base}_blurred{('.mp4' if video else ext)}").replace(os.sep, '/')
    dst = os.path.join(HERE, rel)
    start_time = float(b.get('start', 0))
    cx = [(c, a - b['start'] + start_time if video else None, z - b['start'] + start_time if video else None) for (c, a, z, _e) in boxes]
    if not video and any((e for (*_x, e) in boxes)):
        warn(f"""{b['file']}: image blur applies to the entire block (box "start" and "end" have no effect)""")
    done = dict(src=signature_file(src), boxes=[[list(c), a, z] for (c, a, z) in cx])
    brand = dst + '.json'
    try:
        with open(brand, encoding='utf-8') as f:
            if os.path.exists(dst) and json.load(f) == done:
                return rel
    except (OSError, ValueError):
        pass
    (vw, vh) = size_media(src)
    if not vw:
        raise BuildError(f"could not read dimensions of {b['file']}")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    (filter, exit) = filter_blur(cx, vw, vh)
    tmp = dst + ('.tmp.mp4' if video else '.tmp' + ext)
    if video:
        cmd = ['ffmpeg', '-v', 'error', '-y', '-i', src, '-filter_complex', filter, '-map', exit, '-an', '-c:v', 'libx264', '-crf', '16', '-preset', 'medium', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', tmp]
    else:
        cmd = ['ffmpeg', '-v', 'error', '-y', '-i', src, '-filter_complex', filter, '-map', exit, '-frames:v', '1', '-update', '1', tmp]
    run_ffmpeg(cmd, f"blur {b['file']}")
    os.replace(tmp, dst)
    with open(brand, 'w', encoding='utf-8') as f:
        json.dump(done, f, ensure_ascii=False)
    warn(f"{b['file']}: page uses blurred {rel}. The original remains readable in assets/; move it outside the project before sharing.")
    return rel

