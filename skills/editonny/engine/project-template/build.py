def duration_tween(b):
    if not isinstance(b, dict):
        return 0.0
    d = float(b.get('duration', 0) or 0)
    kf = b.get('keyframes')
    if isinstance(kf, list):
        d = sum((float(k.get('duration', 0) or 0) for k in kf))
    rep = b.get('repeat') or 0
    if rep > 0:
        d *= 1 + rep
    if b.get('stagger'):
        d += float(b['stagger']) * 20
    return d

def window_records(R):
    start_time = end = None
    for (k, _sel, _a, b, t) in R:
        if k == 'start':
            continue
        if k == 'frames':
            ts = [tq for (tq, _) in b]
            if not ts:
                continue
            (t0, t1) = (min(ts), max(ts))
        else:
            (t0, t1) = (t, t + duration_tween(b))
        start_time = t0 if start_time is None else min(start_time, t0)
        end = t1 if end is None else max(end, t1)
    return (start_time, end)

def resolve_blocks(P):
    """Resolve block timings, fill gaps with fullscreen video, and align framed blocks with nearby cuts."""
    bl = []
    for (i, b) in enumerate(P.cfg.get('blocks', [])):
        d = dict(b)
        d['start'] = P.time(b, 'start') if 'start' in b else 0.0
        d['end'] = P.time(b, 'end', after=d['start']) if 'end' in b else P.VDUR
        if d.get('scene') not in SCENES:
            raise BuildError(f"""block {i + 1}: "scene" must be {', '.join(SCENES[:-1])} or {SCENES[-1]}""")
        if d.get('followFace') and d['scene'] not in ('fullscreen', 'frame'):
            raise BuildError(f'Block {i + 1}: followFace supports fullscreen and frame only.')
        if d['scene'] in ('frame', 'greenScreen', 'contain') and d.get('inCut', True):
            for k in [k for k in ('start', 'end') if k in b]:
                c = min(P.cuts, key=lambda c: abs(c - d[k]), default=None)
                if c is not None and abs(c - d[k]) <= 0.35:
                    if abs(c - d[k]) > 0.02:
                        warn(f"block {i + 1} ({d['scene']}): {k} {d[k]:.2f} aligned to cut {c:.2f}")
                    d['_requested' + k.title()] = d[k]
                    d[k] = c
        bl.append(d)
    bl.sort(key=lambda d: d['start'])
    (full, t) = ([], 0.0)
    for d in bl:
        if d['start'] > t + 0.001:
            full.append(dict(scene='fullscreen', start=t, end=d['start']))
        d['start'] = max(d['start'], t)
        if d['end'] > d['start'] + 0.001:
            full.append(d)
        t = max(t, d['end'])
    if t < P.VDUR - 0.001:
        full.append(dict(scene='fullscreen', start=t, end=P.VDUR))
    full[-1]['end'] = max(full[-1]['end'], P.VDUR + 60)
    for (k, d) in enumerate(full):
        if d['scene'] == 'contain':
            background = d.setdefault('background', 'blurred')
            if background not in ('blurred', 'paper') and (not re.match('^#[0-9a-fA-F]{3}([0-9a-fA-F]{3})?$', str(background))):
                raise BuildError(f"contain at {d['start']:.2f} s: background must be blurred, paper, or a hexadecimal color.")
        if d['scene'] != 'frame':
            continue
        previous = full[k - 1]['scene'] if k else None
        d['_close'] = d['start'] if d['start'] < 0.001 else d['start'] + (0.25 if previous == 'greenScreen' else FRAME_CLOSE_DURATION)
        background = d.get('background', 'paper')
        if background not in ('paper', 'blurred'):
            raise BuildError(f"frame at {d['start']:.2f} s: background must be paper or blurred.")
    return full

class Composition:

    def __init__(self, P, T0, T1, mode='compose', hold=0.0, card=0.0):
        (self.P, self.F, self.E) = (P, P.F, P.E)
        (self.W, self.H) = (P.W, P.H)
        self.mode = mode
        self.T0 = round(T0 * FPS) / FPS
        self.T1 = round(T1 * FPS) / FPS
        (self.hold, self.card) = (hold, card)
        self.tail = hold + card
        self.VFIM = min(self.T1, P.VDUR)
        self.DUR = round(self.VFIM - self.T0 + self.tail, 3)
        (self._HT, self._CSS, self.R, self.AUD) = ([], {}, [], [])
        (self.BEHIND, self.PERSON_BEHIND) = ([], [])
        self.BACKGROUNDS = []
        (self.target, self.tracks) = (None, [])
        (self.scenes_js, self.extra_hidden) = ({}, [])
        (self.sounds_sug, self.rectangles, self.n_pieces) = ([], [], 0)
        self.pushed = False
        self.through_end = False
        (self.outside_captions, self.together_ok) = (set(), set())
        self.CAM = '.camera'
        self.FRAME = tuple(P.cfg.get('frame', {}).get('box', self.F['frame']))
        self.FULL = (0, 0, self.W, self.H)
        k = max(self.W / max(1, P.vw), self.H / max(1, P.vh))
        (self.dw, self.dh) = (P.vw * k, P.vh * k)
        (self.ox, self.oy) = ((self.W - self.dw) / 2, (self.H - self.dh) / 2)
        self.PARALLAX_LAYERS = []
        self.last_behind = None
        (self.COMPARISON_HTML, self.voice_outside) = ([], [])
        self.blocks = self._blocks()
        self.zooms = self._zooms()
        if any((b.get('followFace') for b in self.blocks)):
            P.load_track()

    @property
    def HT(self):
        return self.target.HT if self.target is not None else self._HT

    @property
    def CSS(self):
        return self.target.CSS if self.target is not None else self._CSS

    @contextmanager
    def track(self, pid, label, track, layer='pieces'):
        F = Track(pid, label, track, layer)
        self.target = F
        try:
            yield F
        finally:
            self.target = None
        self.tracks.append(F)
        (self.BEHIND if layer == 'behind' else self._HT).append(F)

    def rr(self, t):
        return round(max(0.0, t - self.T0), 3)

    def inside(self, a, b):
        return b > self.T0 and a < self.T1

    @staticmethod
    def _o(d):
        return json.dumps(d, ensure_ascii=False, separators=(',', ':'))

    def _rec(self, r):
        if self.target is not None and (not str(r[1]).startswith(('#stage', '.parallax-background'))):
            self.target.R.append(r)
        else:
            self.R.append(r)

    def FT(self, sel, a, b, t):
        b = dict(b)
        b.setdefault('immediateRender', False)
        self._rec(('ft', sel, a, b, t))

    def TO(self, sel, b, t):
        b = dict(b)
        b.setdefault('immediateRender', False)
        self._rec(('to', sel, None, b, t))

    def SET(self, sel, b, t):
        self._rec(('set', sel, None, b, t))

    def SETQ(self, sel, b, tq):
        """Set at the exact frame, rounding down to milliseconds to avoid a one-frame delay."""
        self._rec(('setq', sel, None, b, tq))

    def FRAMES(self, sel, pairs):
        """Emit deterministic per-frame states for random-access seeking."""
        self._rec(('frames', sel, None, list(pairs), None))

    def START(self, sel, props):
        """Initialize frame zero with a short tween so seeking back to zero restores the state."""
        self.R.append(('start', sel, props, None, None))

    @staticmethod
    def _rt(t, org):
        return round(max(0.0, t - org), 3)

    @staticmethod
    def _rq(t, org):
        return math.floor((t - org) * 1000 + 1e-06) / 1000

    def js(self, R, org, end):
        (o, out) = (self._o, [])
        for (k, sel, a, b, t) in R:
            if k == 'ft':
                out.append(f'tl.fromTo({o(sel)},{o(a)},{o(b)},{self._rt(t, org)});')
            elif k == 'to':
                out.append(f'tl.to({o(sel)},{o(b)},{self._rt(t, org)});')
            elif k == 'set':
                out.append(f'tl.set({o(sel)},{o(b)},{self._rt(t, org)});')
            elif k == 'setq':
                tc = self._rq(t, org)
                if tc >= 0:
                    out.append(f'tl.set({o(sel)},{o(b)},{tc});')
            elif k == 'frames':
                data = []
                for (tq, props) in b:
                    tc = self._rq(tq, org)
                    if 0 <= tc <= end:
                        data.append([tc, props])
                if data:
                    out.append(f'for (const [t, p] of {o(data)}) tl.set({o(sel)}, p, t);')
            elif k == 'start':
                out.append(f"tl.fromTo({o(sel)},{o(a)},{o(dict(a, duration=0.04, ease='none'))},0);")
        return out

    def sound(self, kind, t, db=SOUND_SMALL, piece=''):
        if self.T0 - 0.05 <= t <= self.T0 + self.DUR:
            self.sounds_sug.append(dict(type=kind, at=round(t, 3), db=db, piece=piece))

    def _blocks(self):
        if self.mode == 'cut':
            return [dict(scene='fullscreen', start=0.0, end=self.P.VDUR + 60, zoom=float(self.P.cfg.get('zoom', 1.08)))]
        return resolve_blocks(self.P)

    def block(self, t):
        for b in self.blocks:
            if b['start'] - 1e-06 <= t < b['end']:
                return b
        return self.blocks[-1]

    def caption_enabled(self, b):
        lg = self.P.cfg.get('captions', {})
        if self.mode == 'cut':
            return True
        if 'captions' in b:
            return bool(b['captions'])
        if not lg.get('enabled', True):
            return False
        if b['scene'] == 'frame':
            return bool(lg.get('inFrame', False))
        if b['scene'] == 'greenScreen':
            return bool(lg.get('inGreenScreen', True))
        if b['scene'] == 'compare':
            return False
        return True

    def vid(self, fx, fy):
        """Vid."""
        return (self.ox + fx * self.dw, self.oy + fy * self.dh)

    def face(self, t, b=None):
        """Face."""
        b = b or self.block(t)
        if b.get('followFace') and self.P.track:
            f = self.P.face_tracked(t)
            if f:
                return f
        return self.P.face(t)

    def place(self, t, box, zoom=1.0, b=None):
        """Place."""
        (W, H) = (self.W, self.H)
        f = self.face(t, b)
        (cx, cy) = self.vid((f['x0'] + f['x1']) / 2, (f['y0'] + f['y1']) / 2)
        fwp = float(f.get('wmed') or f['x1'] - f['x0']) * self.dw
        (bx, by, bw, bh) = box
        if bw >= W and bh >= H:
            z = zoom
        else:
            z = max(0.4 * bw / max(1.0, fwp), bw / self.dw, bh / self.dh)
        x = clamp(bw / 2 - z * cx, bw - z * (self.ox + self.dw), -z * self.ox)
        y = clamp(0.42 * bh - z * cy, bh - z * (self.oy + self.dh), -z * self.oy)
        return dict(x=round(x + bx, 1), y=round(y + by, 1), scale=round(z, 4))

    def cam(self, t, b=None):
        """Cam."""
        b = b or self.block(t)
        z = self.zoom_at(t, 'camera')
        if z and self.blocks[z['layout']] is b:
            return self.frame_zoom(z, t)
        return self.cam_base(t, b)

    def cam_base(self, t, b=None):
        b = b or self.block(t)
        if b['scene'] == 'frame':
            return self.place(t, self.FRAME, b=b)
        if b['scene'] == 'evidence':
            z = float(b.get('zoom', 1.0))
            return dict(x=0, y=0, scale=1) if z == 1 else self.place(t, self.FULL, z, b=b)
        if b['scene'] in ('greenScreen', 'compare'):
            return dict(x=0, y=0, scale=1)
        if b['scene'] == 'contain':
            (rx, ry, rw, rh) = self.box_contain(b)
            zc = rw / self.dw
            return dict(x=round(rx - zc * self.ox, 1), y=round(ry - zc * self.oy, 1), scale=round(zc, 4))
        return self.place(t, self.FULL, float(b.get('zoom', self.P.cfg.get('zoom', 1.08))), b=b)

    def box_contain(self, b):
        """Box contain."""
        m = float(b.get('margin', round(0.06 * min(self.W, self.H))))
        zc = min((self.W - 2 * m) / self.dw, (self.H - 2 * m) / self.dh)
        (rw, rh) = (self.dw * zc, self.dh * zc)
        return (round((self.W - rw) / 2, 1), round((self.H - rh) / 2, 1), round(rw, 1), round(rh, 1))

    def frame_at(self, b):
        """Resolve a block frame at a time."""
        if b['scene'] == 'frame':
            return (self.FRAME, self.F['radius'])
        if b['scene'] == 'contain':
            return (self.box_contain(b), int(b.get('radius', self.F['radius'])))
        return (self.FULL, 0)

    def _zooms(self):
        (P, out) = (self.P, [])
        if self.mode == 'cut':
            return out
        for (i, b) in enumerate(self.blocks):
            zs = b.get('zooms') or []
            if not zs:
                continue
            if b['scene'] not in ('fullscreen', 'evidence'):
                raise BuildError(f"""block {b['scene']} at_time {b['start']:.2f} s: "zooms" supports fullscreen and evidence only""")
            target = 'camera' if not (b['scene'] == 'evidence' and b.get('file')) else f'pvw{i}'
            items_list = []
            for (k, z) in enumerate(zs):
                name = f"zoom {k + 1} in block {b['scene']} at_time {b['start']:.2f} s"
                if not isinstance(z, dict):
                    raise BuildError(f'{name}: each zoom must be an object with at, end, and box [x, y, width, height].')
                t0 = P.time(z, 'at', after=max(0.0, b['start'] - 0.3), advance=float(z.get('advance', 0.0)))
                if t0 is None:
                    raise BuildError(f'{name}: missing "at" (cut seconds or a spoken word)')
                if not b['start'] - 0.35 <= t0 < b['end'] - 0.1:
                    raise BuildError(f"""{name}: "at" ({t0:.2f} s) must remain inside the block ({b['start']:.2f} to {b['end']:.2f} s)""")
                t0 = max(t0, b['start'])
                t1 = P.time(z, 'end', after=t0 + 0.05) if 'end' in z else None
                return_motion = t1 is not None
                if t1 is None or t1 > b['end'] - 0.001:
                    if t1 is not None:
                        warn(f"{name}: end exceeds the block; zoom remains until {b['end']:.2f} s.")
                    (t1, return_motion) = (b['end'], False)
                box = z.get('box')
                if box is not None and (not isinstance(box, (list, tuple)) or len(box) != 4 or (not all((0 <= float(v) <= 1 for v in box)))):
                    raise BuildError(f'{name}: box must be [x, y, width, height] in source-video fractions from 0 to 1.')
                dur = float(z.get('duration', 0.45 if box else 0.2))
                items_list.append(dict(layout=i, target=target, t0=round(t0, 3), t1=round(t1, 3), returnMotion=return_motion, dur=dur, returnDuration=float(z.get('returnDuration', max(dur, 0.35))), box=[float(v) for v in box] if box else None, scale=float(z['scale']) if z.get('scale') else None, ease=z.get('ease', 'power3.inOut' if box else 'power2.out'), sound=z.get('sound', 'whoosh')))
            items_list.sort(key=lambda z: z['t0'])
            for (a_, b_) in zip(items_list, items_list[1:]):
                if a_['t1'] > b_['t0'] - 0.001:
                    (a_['t1'], a_['returnMotion']) = (b_['t0'], False)
                elif a_['returnMotion'] and a_['t1'] + a_['returnDuration'] > b_['t0']:
                    a_['returnDuration'] = max(0.1, b_['t0'] - a_['t1'])
            out += items_list
        return out

    def end_without_cut(self, t, dur):
        """End without cut."""
        return t if any((t + 0.001 < c <= t + dur + 0.001 for c in self.P.cuts)) else t + dur

    def zoom_at(self, t, target):
        for z in self.zooms:
            if z['target'] == target and z['t0'] - 1e-06 <= t < z['t1'] - 1e-06:
                return z
        return None

    def _media_px(self, target):
        """Media px."""
        if target == 'camera':
            return (self.P.vw, self.P.vh, 'cover')
        b = self.blocks[int(target[3:])]
        (w, h) = size_media(os.path.join(HERE, b['file']))
        return (w or self.W, h or self.H, b.get('fit', 'cover'))

    def frame_zoom(self, z, t):
        (W, H) = (self.W, self.H)
        if z['box'] is None:
            s = z['scale'] or 1.3
            if z['target'] == 'camera':
                return self.place(t, self.FULL, s)
            return dict(x=round(W / 2 * (1 - s), 1), y=round(H / 2 * (1 - s), 1), scale=round(s, 4))
        (vw, vh, enc) = self._media_px(z['target'])
        k = min(W / vw, H / vh) if enc == 'contain' else max(W / vw, H / vh)
        (ox, oy) = ((W - vw * k) / 2, (H - vh * k) / 2)
        (x0, y0, cw, ch) = z['box']
        (bx, by, bw, bh) = (ox + x0 * vw * k, oy + y0 * vh * k, max(1.0, cw * vw * k), max(1.0, ch * vh * k))
        s = z['scale'] or clamp(0.85 * min(W / bw, H / bh), 1.0, 6.0)
        if enc == 'contain':
            x = clamp(W / 2 - s * (bx + bw / 2), W - s * W, 0)
            y = clamp(H / 2 - s * (by + bh / 2), H - s * H, 0)
        else:
            x = clamp(W / 2 - s * (bx + bw / 2), W - s * (ox + vw * k), -s * ox)
            y = clamp(H / 2 - s * (by + bh / 2), H - s * (oy + vh * k), -s * oy)
        return dict(x=round(x, 1), y=round(y, 1), scale=round(s, 4))

    def frame_before_zoom(self, z):
        for p in self.zooms:
            if p is not z and p['target'] == z['target'] and (p['t0'] < z['t0']) and (p['t1'] >= z['t0'] - 1e-06):
                return self.frame_zoom(p, z['t0'])
        if z['target'] == 'camera':
            return self.cam_base(z['t0'], self.blocks[z['layout']])
        return dict(x=0, y=0, scale=1)

    def frame_base(self, z, t):
        return self.cam_base(t, self.blocks[z['layout']]) if z['target'] == 'camera' else dict(x=0, y=0, scale=1)

    def clip(self, box, rad):
        (x, y, w, h) = box
        r = lambda v: f'{round(v, 1):g}'
        return f'inset({r(y)}px {r(self.W - x - w)}px {r(self.H - y - h)}px {r(x)}px round {rad}px)'

    def person_tf(self, b):
        """Person tf."""
        (W, H) = (self.W, self.H)
        pos = b.get('position', 'right')
        s = float(b.get('height', 0.8 if pos == 'center' else 0.62))
        f = self.P.face(b['start'] + 0.05)
        fx = self.vid((f['x0'] + f['x1']) / 2, 0)[0]
        target = {'right': 0.7, 'left': 0.3, 'center': 0.5}.get(pos, 0.7) * W
        tx = target - s * fx
        st = self._person_stats(b)
        if st:
            if pos == 'right' and st.get('touch_right', 0) > 0.3:
                tx = W - s * W
            elif pos == 'left' and st.get('touch_left', 0) > 0.3:
                tx = 0
            side_inside = st.get('touch_left', 0) if pos == 'right' else st.get('touch_right', 0)
            if pos != 'center' and side_inside > 0.3:
                warn(f"green screen {b['start']:.1f}s: the camera crops the body on the inner side. Change side or use center.")
        return (round(tx, 1), round(H - s * H, 1), round(s, 4))

    def person_window(self, cutout='assets/person.webm'):
        """Person window."""
        p = os.path.join(HERE, os.path.splitext(cutout)[0] + '.json')
        if not os.path.exists(p):
            return (0.0, self.P.VDUR)
        with open(p, encoding='utf-8') as f:
            d = json.load(f)
        return (float(d.get('start', 0.0)), float(d.get('end', self.P.VDUR)))

    def _person_stats(self, b):
        p = os.path.join(HERE, 'assets', 'person.json')
        if not os.path.exists(p):
            return None
        with open(p, encoding='utf-8') as f:
            d = json.load(f)
        for r in d.get('intervals', []):
            if r['start'] - 0.001 <= b['start'] + 0.05 < r['end']:
                return r.get('stats') or {}
        return None

    def face_screen(self, t):
        """Face screen."""
        b = self.block(t)
        if b['scene'] == 'evidence' and b.get('file') or b['scene'] == 'compare':
            return None
        if b['scene'] == 'greenScreen':
            f = self.P.face(t)
            (tx, ty, s) = self.person_tf(b)
            c = dict(x=tx, y=ty, scale=s)
        else:
            f = self.face(t, b)
            c = self.cam(t, b)
        ((ax, ay), (bx_, by_)) = (self.vid(f['x0'], f['y0']), self.vid(f['x1'], f['y1']))
        (x0, x1) = (c['x'] + c['scale'] * ax, c['x'] + c['scale'] * bx_)
        (y0, y1) = (c['y'] + c['scale'] * ay, c['y'] + c['scale'] * by_)
        return dict(x0=x0, x1=x1, y0=y0, y1=y1, top=y0 - 0.35 * (y1 - y0))

    def placement(self, t, w, h, where='auto', name=''):
        if isinstance(where, (list, tuple)):
            return (int(where[0]), int(where[1]))
        F = self.F
        (sx0, sy0, sx1, sy1) = F['safeArea']
        b = self.block(t)
        k = b['scene']
        if where == 'bottomLeft' or (k == 'frame' and where == 'auto'):
            (ax0, ay0, ax1, ay1) = F['lowerLeftArea'] if where == 'bottomLeft' else F['frameArea']
            if h > ay1 - ay0 or w > ax1 - ax0:
                warn(f'{name}: the object ({w}x{h}) exceeds the available frame area')
            return (int((ax0 + ax1) / 2 - w / 2), int(ay0 + max(0, (ay1 - ay0 - h) * 0.35)))
        cx = (sx0 + sx1) / 2
        if k in ('evidence', 'greenScreen', 'compare') or where == 'top':
            return (int(cx - w / 2), int(sy0 + 20))
        r = self.face_screen(t)
        if not r:
            return (int(cx - w / 2), int(sy0 + 20))
        above = r['top'] - 30 - (sy0 + 20)
        if where in ('auto', 'above') and above >= h:
            return (int(cx - w / 2), int(max(sy0 + 20, r['top'] - 40 - h)))
        if self.format_landscape() and where == 'auto':
            fx = (r['x0'] + r['x1']) / 2
            if fx > self.W / 2 and r['x0'] - 60 - sx0 >= w:
                return (int((sx0 + r['x0'] - 40) / 2 - w / 2), int(clamp((r['y0'] + r['y1']) / 2 - h / 2, sy0, sy1 - h)))
            if fx <= self.W / 2 and sx1 - r['x1'] - 60 >= w:
                return (int((r['x1'] + 40 + sx1) / 2 - w / 2), int(clamp((r['y0'] + r['y1']) / 2 - h / 2, sy0, sy1 - h)))
        y = r['y1'] + 40
        if y + h <= sy1:
            return (int(cx - w / 2), int(y))
        warn(f'{name}: does not fit without touching the face (at {t:.2f} s). Use a framed block or a smaller animation.')
        return (int(cx - w / 2), int(sy0 + 20))

    def format_landscape(self):
        return self.W > self.H

    def reserve(self, t0, t1, x, y, w, h):
        self.rectangles.append((t0, t1, x, y, w, h))

    def css(self, key, text):
        if key not in self.CSS:
            v = {k: v2 for (k, v2) in self.F.items() if isinstance(v2, (int, float))}
            v.update(self.E)
            v.update(W=self.W, H=self.H)
            self.CSS[key] = Template(text).substitute(v)

def rich(text):
    """Rich."""
    parts = escape(str(text)).split('*')
    return ''.join((f'<b>{p}</b>' if i % 2 else p for (i, p) in enumerate(parts)))

def width_text(text, fs, weight=900):
    clean = str(text).replace('*', '')
    factor = 0.74 if clean.upper() == clean else 0.64
    return len(clean) * fs * factor * (1 if weight >= 800 else 0.9)

def graphemes(text):
    """Keep combining accents attached to their base characters."""
    out = []
    for ch in unicodedata.normalize('NFC', text):
        if out and unicodedata.combining(ch):
            out[-1] += ch
        else:
            out.append(ch)
    return out

def frame_closing(M, t):
    """Frame closing."""
    for b in M.blocks:
        if b['scene'] == 'frame' and b['start'] - 0.5 - 1e-06 <= t < b.get('_close', b['start']) - 0.001:
            return b
    return None

def afterTime(times, t0, step=0.15):
    """Offset sequential item times after entry."""
    (out, previous) = ([], None)
    for t in times:
        t2 = max(t, t0) if previous is None else max(t, t0, previous + step)
        out.append(t2)
        previous = t2
    return out
END_WITHOUT_EXIT = 0.35

def entry_exit(M, p, default):
    P = M.P
    M.pushed = M.through_end = False
    t_in = P.time(p, 'at', advance=float(p.get('advance', 0.1)))
    if t_in is None:
        raise BuildError(f"""animation {p.get('id', '?')}: missing "at" (seconds or a spoken word)""")
    t_out = P.time(p, 'exit', after=t_in + 0.05, advance=0.05)
    if t_out is None:
        t_out = t_in + default
    if t_out >= P.VDUR - 0.25:
        if p.get('type') == 'behindPerson' and M.hold:
            warn(f"{p.get('id')}: behind-person text ends with speech at {P.VDUR:.2f} s; the held final frame has no person cutout.")
            t_out = min(t_out, P.VDUR)
        else:
            t_out = P.VDUR + M.hold + END_WITHOUT_EXIT
            M.through_end = True
    frame = frame_closing(M, t_in)
    if frame is not None:
        new = round(frame['_close'] + 0.02, 3)
        warn(f"{p.get('id')}: enters at {new:.2f} s, after the frame closed (requested {t_in:.2f}; frame enters at {frame['start']:.2f} and takes {new - frame['start']:.1f} s)")
        (t_in, M.pushed) = (new, True)
    b = M.block(t_in)
    if b['scene'] in ('frame', 'greenScreen', 'evidence', 'contain', 'compare') and t_out > b['end'] - 0.1 and (b['end'] < P.VDUR):
        warn(f"{p.get('id')}: exit at_time {b['end'] - 0.1:.2f} s, before the block ends {b['scene']} (pedia {t_out:.2f})")
        t_out = b['end'] - 0.1
    t_out = max(t_out, t_in + 0.4)
    if M.target is not None:
        M.target.exit = (t_in, t_out)
    return (t_in, t_out)

def trim_items(pid, items, times, t_out, name='item'):
    """Trim items."""
    keep = [k for (k, t) in enumerate(times) if t <= t_out - 0.35]
    if len(keep) < len(times):
        outside = ', '.join((str(items[k].get('text', k + 1)) for k in range(len(times)) if k not in keep))
        warn(f'{pid}: {name} "{outside}" occurs after exit ({t_out:.2f} s) and was omitted.')
    if not keep:
        raise BuildError(f'{pid}: no {name} fits before exit ({t_out:.2f} s).')
    return ([items[k] for k in keep], [times[k] for k in keep])

def measure_label(text, s, lmax=None):
    """Measure label."""
    fs = round(46 * s)
