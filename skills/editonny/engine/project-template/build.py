def backgrounds_contain(M, boundaries):
    """Backgrounds contain."""
    outputs = {id(A): (B, any((abs(c - B['start']) < 0.05 for c in M.P.cuts))) for (A, B) in boundaries}
    entries = {id(B): (A, any((abs(c - B['start']) < 0.05 for c in M.P.cuts))) for (A, B) in boundaries}
    for (i, b) in enumerate(M.blocks):
        if b['scene'] != 'contain':
            continue
        (next, in_cut) = outputs.get(id(b), (None, True))
        animate = next is not None and next['scene'] != 'greenScreen' and (not in_cut)
        end_b = b['end'] + (0.6 if animate else 0)
        if not M.inside(b['start'], end_b):
            continue
        (a, z) = (max(b['start'], M.T0), min(end_b, M.VFIM))
        if b['end'] >= M.P.VDUR - 0.001 and M.VFIM >= M.P.VDUR - 0.001:
            z = M.T0 + M.DUR
        M.css('contain', '.contain-background{position:absolute;inset:0}\n.cborda{position:absolute;opacity:0;box-shadow:0 18px 50px rgba(0,0,0,.45),0 0 0 3px rgba(255,255,255,.14)}')
