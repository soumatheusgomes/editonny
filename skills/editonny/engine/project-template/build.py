        if A['w'] * A['h'] != B['w'] * B['h'] and abs(ra / rb - 1) <= 0.02:
            smaller = A if A['w'] * A['h'] < B['w'] * B['h'] else B
            warn(f"{name}: side {smaller['key']} has lower source resolution ({smaller['w']}x{smaller['h']}); both are displayed at the same size.")
        (a, z) = (max(b['start'], M.T0), min(b['end'], M.VFIM))
        dd = round(z - a, 3)
        for L in (A, B):
            L['ms'] = round(L['start'] + (a - b['start']), 3)
            if L['video']:
                dur = duration_media(os.path.join(HERE, L['file']))
                if dur and L['ms'] + dd > dur + 0.05:
                    warn(f"{name}: side {L['key']} ({L['name']}) lasts {dur:.2f} s; check that the requested interval fits.")
        (boxes, lab) = fit_comparison(M, mode, ra)
