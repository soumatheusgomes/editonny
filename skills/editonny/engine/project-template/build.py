def stop_studio(npx, name, silent=False):
    style = read_state()
    visible = studios_this_project([style.get('port')])
    if not visible:
        hf(npx, ['preview', '--stop', '--json'], timeout=120)
        delete_state()
        if not silent:
            print(f'ok: no Studio for "{name}" is running (checked ports beginning at {FIRST_PORT}).')
        return
    ports = ', '.join((str(p) for (p, _c) in visible))
    for attempt in range(3):
        for (port, _cfg) in visible:
            hf(npx, ['preview', '--stop', '--json', '--port', str(port)], timeout=120)
        end = time.time() + 3 + 3 * attempt
        while time.time() < end and any((still_this(p) for (p, _c) in visible)):
            time.sleep(0.5)
        visible = [(p, c) for (p, c) in visible if still_this(p)]
        if not visible:
            break
    if visible:
        for (port, cfg) in visible:
            pid = int(cfg.get('pid') or 0)
            if pid > 0 and pid != os.getpid():
                try:
                    os.kill(pid, signal.SIGTERM)
                except OSError:
                    pass
        end = time.time() + 10
        while time.time() < end and any((still_this(p) for (p, _c) in visible)):
            time.sleep(0.5)
        visible = [(p, c) for (p, c) in visible if still_this(p)]
    if visible:
        (p, c) = visible[0]
        raise BuildError(f"Studio is still running on port {p} (process {c.get('pid')}). Stop that process explicitly.")
    delete_state()
    if not silent:
        print(f'ok: Studio for "{name}" stopped (verified closed ports: {ports}).')

def studio(port=None, stop=False, open=True):
    npx = find_npx()
    if not npx:
        raise BuildError('Node (npx) was not found. Install Node.js 22 or newer with npx on PATH and run editonny doctor.')
    name = os.path.basename(HERE.rstrip('/\\'))
    if stop:
        stop_studio(npx, name)
        return
    if not os.path.exists(os.path.join(HERE, 'index.html')):
        raise BuildError('index.html is missing: run python3 build.py cut (or sample/compose) before Studio')
    check_node(npx)
    version = version_hf()
    visible = studios_this_project([read_state().get('port'), port])
    for (p, cfg) in visible:
        if (port is None or p == port) and cfg.get('version') in (None, version):
            url = url_studio(p, cfg.get('projectName') or name)
            write_state(dict(port=p, url=url, version=version, pid=cfg.get('pid')))
            print(f'ok: Studio is already running · {url}')
            return
    if visible:
        (p, cfg) = visible[0]
        if cfg.get('version') not in (None, version):
            print(f"  Restarting HyperFrames {cfg.get('version')} with pinned version {version}.")
        stop_studio(npx, name, silent=True)
    if port is not None and port_free(port) != port:
        raise BuildError(f'Port {port} is busy. Try python3 build.py studio --port {port_free(port + 1)}')
    if port is None:
        port = port_free(FIRST_PORT)
    args = ['preview', '--background', '--port', str(port), '--json'] + ([] if open else ['--no-open'])
    r = hf(npx, args, timeout=600)
    d = (json_from_output(r.stdout) or {}).get('result') or {}
    if r.returncode != 0 or not d:
        raise BuildError('Studio did not start: ' + (r.stderr or r.stdout).strip()[-600:])
    port = int(d.get('port', port))
    server = d.get('serverUrl') or f'http://127.0.0.1:{port}'
    url = d.get('studioUrl') or url_studio(port, name)
    if not responds(server, 120):
        raise BuildError(f"Studio started but did not respond at {server}. Check the log: {d.get('logPath', '')}")
    write_state(dict(port=port, url=url, version=version, pid=d.get('pid')))
    print(f'ok: Studio running (HyperFrames {version}) · {url}')
    print('  The timeline shows video, captions, animations, scenes, voice, and sounds. Studio reloads')
    print('  after each build. Store Studio edits in project.json before rebuilding.')
    print('  stop: python3 build.py studio --stop')
