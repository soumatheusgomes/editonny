def norm(s):
    s = s.strip().lower().strip('.,!?…:;"\'()«»“”')
    return ''.join((c for c in unicodedata.normalize('NFD', s) if unicodedata.category(c) != 'Mn'))

def is_skill(p):
    return bool(p) and os.path.isfile(os.path.join(os.path.expanduser(p), 'helpers', 'matte.py'))

def template_engine():
    """Return the engine directory when this file runs inside its original template."""
    parent = os.path.dirname(HERE)
    return parent if is_skill(parent) and os.path.basename(HERE) == 'project-template' else None

def write_project_field(key, value, directory=None):
    """Update one top-level project field while preserving formatting where possible."""
    p = os.path.join(directory or HERE, 'project.json')
    with open(p, encoding='utf-8') as f:
        txt = f.read()
    v = json.dumps(value, ensure_ascii=False)
    pat = re.compile('("%s"\\s*:\\s*)("(?:[^"\\\\]|\\\\.)*"|null)' % re.escape(key))
    if pat.search(txt):
        new = pat.sub(lambda m: m.group(1) + v, txt, count=1)
    else:
        new = re.sub('^\\s*\\{', lambda m: m.group(0) + f'\n  "{key}": {v},', txt, count=1)
    try:
        data = json.loads(new)
        assert data.get(key) == value
    except (ValueError, AssertionError):
        data = json.loads(txt)
        data[key] = value
        new = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    with open(p, 'w', encoding='utf-8') as f:
        f.write(new)

def register_engine(cfg):
    """Record the explicitly selected engine directory for generated projects."""
    current = str(cfg.get('skill') or '').strip()
    if current:
        if not is_skill(current):
            warn(f'project.json skill ({current}) has no helpers/matte.py: check the engine path')
        return
    if template_engine():
        return
    env = os.environ.get('EDITONNY_ENGINE_DIR') or ''
    if is_skill(env):
        cand = os.path.abspath(os.path.expanduser(env))
        cfg['skill'] = cand
        write_project_field('skill', cand)
        print(f'  engine recorded in project.json (EDITONNY_ENGINE_DIR): {cand}')
        return
    warn('Project has no engine path. Set "skill" in project.json; new records it automatically.')

def project_engine(cfg):
    """Resolve the engine from project configuration, template location, or environment."""
    for cand in (str(cfg.get('skill') or '').strip(), template_engine() or '', os.environ.get('EDITONNY_ENGINE_DIR') or ''):
        if is_skill(cand):
            return os.path.abspath(os.path.expanduser(cand))
    return None

