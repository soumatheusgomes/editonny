    (P, F, s) = (M.P, M.F, M.F['scale'])
    fr = p['front']
    fr = {'image': fr} if isinstance(fr, str) else dict(fr)
    img = str(fr.get('image') or fr.get('file') or '')
    fid = f'{pid}-front'
