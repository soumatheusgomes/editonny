def signature_file(p):
    value = hashlib.sha256()
    with open(p, 'rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            value.update(chunk)
    return value.hexdigest()

def ffprobe_value(p, entries, stream='v:0'):
    r = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', stream, '-show_entries', entries, '-of', 'csv=p=0', p], capture_output=True, text=True, encoding='utf-8', errors='replace')
    return r.stdout.strip().split('\n')[0].split(',') if r.returncode == 0 else []

def size_media(p):
    v = ffprobe_value(p, 'stream=width,height')
    try:
        return (int(v[0]), int(v[1]))
    except (ValueError, IndexError):
        return (None, None)
REDUCED_IMAGES = ('.png', '.jpg', '.jpeg', '.webp')

def resize_image(rel, w, h, fit='contain'):
    """Resize a media image for the requested dimensions."""
    src = os.path.join(HERE, rel)
    ext = os.path.splitext(rel)[1].lower()
    if ext not in REDUCED_IMAGES or not os.path.isfile(src) or (not shutil.which('ffmpeg')) or (w < 1) or (h < 1):
        return rel
    (iw, ih) = size_media(src)
    if not iw or not ih:
        return rel
    k = (max if fit == 'cover' else min)(w / iw, h / ih)
    if k >= 0.999:
        return rel
    (tw, th) = (iw * k, ih * k)
    (tw, th) = (math.ceil(tw - 1e-06), math.ceil(th - 1e-06)) if fit == 'cover' else (max(1, round(tw)), max(1, round(th)))
    base = os.path.splitext(os.path.basename(rel))[0]
    jpg = ext in ('.jpg', '.jpeg')
    origin = hashlib.sha1(rel.replace(os.sep, '/').encode()).hexdigest()[:8]   # Same-named images in other folders.
    dst_rel = f"{GENERATED_DIR}/{base}_{origin}_{tw}x{th}{('.jpg' if jpg else '.png')}".replace(os.sep, '/')
    dst = os.path.join(HERE, dst_rel)
    if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
        return dst_rel
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    filter = f'scale={tw}:{th}:flags=area' if jpg else f'format=gbrap,premultiply=inplace=1,scale={tw}:{th}:flags=area,unpremultiply=inplace=1,format=rgba'
    cmd = ['ffmpeg', '-v', 'error', '-y', '-i', src, '-vf', filter, '-frames:v', '1', '-update', '1']
    run_ffmpeg(cmd + (['-q:v', '2'] if jpg else []) + [dst], f'resize {rel} to {tw}x{th}')
    return dst_rel

