    def _waveform_times(self, raw):
        """Apply waveform starts only when at least 80 percent match the transcript; keep user speech unchanged."""
        try:
            d = self._json('waveform_words.json', optional=True)
        except ValueError:
            d = None
        list = (d or {}).get('words') if isinstance(d, dict) else None
        if not list:
            return 'whisper'
        by_time = {}
        for r in list:
            try:
                by_time.setdefault(round(float(r['whisper']), 2), []).append(r)
            except (KeyError, TypeError, ValueError):
                continue
        (matched, change) = (0, [])
        for w in raw:
            for r in by_time.get(round(w['start'], 2), []):
                if norm(str(r.get('text', ''))) == norm(w['text']):
                    new = float(r['start'])
                    if abs(new - w['start']) <= 0.45:
                        change.append((w, new))
                    matched += 1
                    break
        if matched < 0.8 * len(raw):
            warn(f'waveform_words.json does not match the transcript ({matched} of {len(raw)} words). Run helpers/align_words.py again for this cut.')
            return 'whisper'
        for (w, new) in change:
            w['start'] = round(new, 3)
            w['end'] = round(max(w['end'], new + 0.05), 3)
        return 'waveform'

    def time_word(self, expr, after=0.0, end=False):
        target = [norm(x) for x in str(expr).split()]
        ws = self.words
        for (i, w) in enumerate(ws):
            if w['start'] < after - 1e-06 or i + len(target) > len(ws):
                continue
            if all((norm(ws[i + k]['text']).startswith(a) for (k, a) in enumerate(target))):
                return ws[i + len(target) - 1]['end'] if end else w['start']
        raise BuildError(f'Could not find "{expr}" after {after:.2f} s. Inspect words: python3 build.py words {max(0, after - 2):.0f} {after + 12:.0f}')

    def time(self, d, key, after=0.0, advance=0.0, end=False):
        """Resolve seconds or a spoken-word anchor, honoring the after constraint."""
        v = d.get(key)
        if v is None:
            return None
        if isinstance(v, (int, float)):
            return float(v)
        if isinstance(v, str):
            try:
                return float(v.replace(',', '.'))
            except ValueError:
                base = d.get(key + 'After')
                if base is None:
                    base = max(float(d.get('after', 0)), after)
                return self.time_word(v, float(base), end) - advance
        raise BuildError(f'"{key}" must be a number (seconds) or a spoken word')

    def face(self, t):
        last = None
        for s in self.faces:
            if s.get('face'):
                last = s['face']
            if s['start'] - 0.002 <= t < s['end'] - 0.002 and s.get('face'):
                return s['face']
        return last or dict(x0=0.35, y0=0.3, x1=0.65, y1=0.47)
    track = None

    def load_track(self):
        """Load smoothed 10 Hz face measurements, regenerating stale measurements through the engine."""
        if self.track is not None:
            return self.track
        p = os.path.join(self.edit, 'face_track.json')
        cut = os.path.join(self.edit, 'cut.mp4')
        if not os.path.exists(cut):
            raise BuildError(f'"followFace" measures the face in cut.mp4, which was not found: {cut}')
        d = read_optional_json(p)
        if not (isinstance(d, dict) and d.get('version') == 1 and (d.get('video_sig') == signature_ns(cut))):
            measure_face(self)
            d = read_optional_json(p)
            if not isinstance(d, dict) or not d.get('shots'):
                raise BuildError(f'face measurement did not write {p}')
        for tm in d['shots']:
            tm['_ts'] = [pt[0] for pt in tm.get('points') or []]
        self.track = d
        return d

    def face_tracked(self, t):
        """Interpolate a measured face rectangle within its shot; return None outside tracked coverage."""
        d = self.track
        if not d:
            return None
        for tm in d['shots']:
            if tm['start'] - 0.002 <= t < tm['end'] - 0.002:
                (pts, ts) = (tm.get('points') or [], tm.get('_ts') or [])
                if not pts:
                    return None
                k = bisect.bisect_right(ts, t)
                if k <= 0:
                    p = pts[0]
                elif k >= len(pts):
                    p = pts[-1]
                else:
                    (a, b) = (pts[k - 1], pts[k])
                    u = (t - a[0]) / max(1e-06, b[0] - a[0])
                    p = [a[i] + (b[i] - a[i]) * u for i in range(5)]
                (cx, cy, w, h) = (p[1], p[2], p[3], p[4])
                return dict(x0=cx - w / 2, x1=cx + w / 2, y0=cy - h / 2, y1=cy + h / 2, wmed=float(tm.get('w_med') or w), tracked=True)
        return None

