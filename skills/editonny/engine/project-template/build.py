def transition_contain(M, A, B, t, in_cut):
    """Transition contain."""
    (ka, kb) = (A['scene'], B['scene'])
    ((qa, ra), (qb, rb)) = (M.frame_at(A), M.frame_at(B))
    (paper_a, paper_b) = (ka in ('frame', 'greenScreen', 'contain'), kb in ('frame', 'greenScreen', 'contain'))
    if kb == 'greenScreen':
        M.TO('#frame', {'opacity': 0, 'duration': 0.25}, t)
        M.sound('whoosh', t + 0.1, SOUND_SMALL, 'greenScreen')
        return
    if ka == 'greenScreen':
        M.SET('#frame', {'clipPath': M.clip(qb, rb)}, t)
        M.SET(M.CAM, M.cam(t, B), t)
        M.FT('#frame', {'opacity': 0}, {'opacity': 1, 'duration': 0.25}, t)
        M.sound('pop', t + 0.1, SOUND_SMALL, 'contain')
        return
    dur = 0.6 if kb == 'contain' else 0.55
    if in_cut:
        M.SET('#frame', {'clipPath': M.clip(qb, rb)}, t)
        M.SET(M.CAM, M.cam(t, B), t)
    else:
        M.SET(M.CAM, M.cam(t, A), t)
