def style_caption(M):
    lg = M.P.cfg.get('captions', {}) or {}
    style = norm(str(lg.get('style', 'standard'))).replace(' ', '_')
    if style in CUSTOM_CAPTION_STYLES:
        raise BuildError(f'''Caption style "{lg.get('style')}" requires a custom scene. Disable captions for that interval with captions false or hidesCaptions. Template styles: {', '.join(CAPTION_STYLES)}.''')
    if style not in CAPTION_STYLES:
        raise BuildError(f'''captions.style must be {' or '.join(CAPTION_STYLES)} (pediu "{lg.get('style')}")''')
    return 'standard' if M.mode == 'cut' else style

def captions(M):
    (P, F) = (M.P, M.F)
    lg = P.cfg.get('captions', {}) or {}
    style = style_caption(M)
    hide = []
    if M.mode != 'cut':
        hide = [(P.time(dict(start=x[0]), 'start'), P.time(dict(end=x[1]), 'end')) for x in lg.get('hide', [])]
        for (i, pp) in enumerate(P.cfg.get('animations', [])):
            if pp.get('type') == 'lettering' and (pp.get('id') or f'a{i + 1}') in M.together_ok:
                continue
            if pp.get('hidesCaptions', pp.get('type') == 'lettering'):
                a = P.time(pp, 'at') or 0
                hide.append((a - 0.1, P.time(pp, 'exit', after=a) or a + 1.5))
        hide += M.extra_hidden
    max_l = int(lg.get('maxChars', F['maxChars'] if style == 'standard' else F['subtleMaxChars']))
    max_p = max(1, int(lg.get('maxWords', 3)))

    def enabled(t):
        if any((a <= t < b for (a, b) in hide)):
            return False
        if not M.caption_enabled(M.block(t)):
            return False
        return M.caption_enabled(M.block(t + 0.3))
    outside = M.outside_captions if M.mode != 'cut' else set()
    (phrases, cur) = ([], [])
    for (k, w) in enumerate(P.words):
        if w['end'] <= M.T0 + 0.05 or w['start'] >= M.VFIM - 0.05 or (not enabled(w['start'])) or (k in outside):
            if cur:
                phrases.append(cur)
                cur = []
            continue
        if cur and w['start'] - cur[-1]['end'] > 0.6:
            phrases.append(cur)
            cur = []
        cur.append(w)
        if w['text'][-1] in ',.?!…':
            phrases.append(cur)
            cur = []
    if cur:
        phrases.append(cur)
    clean = [c for f in phrases for c in split_phrase(f, max_p, max_l)]
    stops = sorted([b['start'] for b in M.blocks] + [x for ab in hide for x in ab] + [M.VFIM])

    def window(i):
        c = clean[i]
        a = c[0]['start']
        limit = min([x for x in stops if x > a + 0.05] + ([clean[i + 1][0]['start']] if i + 1 < len(clean) else []) + [M.VFIM])
        b = min(c[-1]['end'] + 0.12, limit)
        return (a, max(b, min(a + 0.35, limit)))

    def join(x, y):
        return y[0]['start'] - x[-1]['end'] <= 0.6 and x[-1]['text'][-1] not in '.?!…' and (not any((x[0]['start'] + 0.05 < p <= y[-1]['end'] for p in stops)))
    changed = True
    while changed:
        changed = False
        for (i, c) in enumerate(clean):
            (a, b) = window(i)
            if len(c) != 1 or b - a >= 0.3:
                continue
            cand = ([i - 1] if i > 0 and join(clean[i - 1], c) else []) + ([i + 1] if i + 1 < len(clean) and join(c, clean[i + 1]) else [])
            if not cand:
                continue
            j = min(cand, key=lambda j: len(' '.join((x['text'] for x in clean[j]))))
            clean[j] = clean[j] + c if j < i else c + clean[j]
            del clean[i]
            changed = True
            break
    if style == 'subtle':
        fs = F['subtleCaptionFontSize']
        hcap = round(fs * 1.55)
        M.css('captions', '.cap{position:absolute;left:40px;right:40px;text-align:center;white-space:nowrap;opacity:0;z-index:50}\n.cap span{display:inline-block;font-weight:700;color:#ffffff;line-height:1.25;letter-spacing:.2px;padding:.1em .5em .14em;\n  border-radius:.45em;background:rgba(18,14,28,.55);text-shadow:0 1px 2px rgba(0,0,0,.35)}')
    else:
        fs = F['captionFontSize']
        hcap = round(fs * 1.3)
        M.css('captions', '.cap{position:absolute;left:40px;right:40px;text-align:center;white-space:nowrap;font-weight:900;color:#ffffff;\n  opacity:0;letter-spacing:.5px;-webkit-text-stroke:10px $captionOutline;paint-order:stroke fill;text-shadow:0 6px 18px rgba(0,0,0,.45);z-index:50}')
    (n, last) = (0, None)
    for (i, c) in enumerate(clean):
        (a, b) = window(i)
        if b <= M.T0:
            continue
        box = box_caption(M, a)
        text = ' '.join((x['text'] for x in c)).rstrip(',.')
        width = measure_text(text.upper() if style == 'standard' else text, 'Montserrat', 900 if style == 'standard' else 700, fs)
        top = top_caption(M, a, b, hcap, last, box, width + (20 if style == 'standard' else 0.9 * fs) + 24)
        last = top
        if style == 'standard':
            text = text.upper()
        start_time = max(a, M.T0)
        placement = f'top:{top}px;font-size:{fs}px'
        if box:
            placement += f';left:{box[0]}px;right:auto;width:{box[1]}px'
        content = escape(text) if style == 'standard' else f'<span>{escape(text)}</span>'
        M._HT.append(f'<div class="cap caption-cue clip" id="cap{i}" data-start="{M.rr(start_time)}" data-duration="{round(b - start_time, 3)}" data-track-index="{TRACK_CAPTION}" data-track-kind="captions" data-timeline-label="Captions · {escape(text)}" style="{placement}">{content}</div>')
        left = box[0] if box else max(0, (M.W - width) / 2 - fs)
        right = box[0] + box[1] if box else min(M.W, (M.W + width) / 2 + fs)
        M.overlay_masks.append({'start': max(0, a - M.T0), 'end': b - M.T0,
                                'box': [left / M.W, max(0, top - 8) / M.H, right / M.W, min(M.H, top + hcap + 22) / M.H]})
        M.FT(f'#cap{i}', {'opacity': 0, 'y': 14}, {'opacity': 1, 'y': 0, 'duration': 0.12}, a)
        M.SET(f'#cap{i}', {'opacity': 0}, b)
        n += 1
    return n

def split_phrase(ws, max_p, max_l):
    """Split phrase."""
    n = len(ws)
    if n <= 1:
        return [ws] if ws else []

    def fits(i, j):
        return j - i == 1 or (j - i <= max_p and len(' '.join((w['text'] for w in ws[i:j]))) <= max_l)

    def cost(i, j):
        c = 0.1 * (j - i) ** 2
        if j - i == 1:
            c += 4.0
        if j < n:
            if norm(ws[j - 1]['text']) in NO_BREAK_AFTER:
                c += 3.0
            c -= 2.0 * clamp(ws[j]['start'] - ws[j - 1]['end'], 0.0, 0.6)
        return c
    best = [None] * (n + 1)
    best[0] = (0, 0.0, [])
    for j in range(1, n + 1):
        for i in range(max(0, j - max_p), j):
            if best[i] is None or not fits(i, j):
                continue
            (q, c, cuts) = best[i]
            cand = (q + 1, round(c + cost(i, j), 6), cuts + [(i, j)])
            if best[j] is None or cand[:2] < best[j][:2]:
                best[j] = cand
    return [ws[i:j] for (i, j) in best[n][2]]

def box_caption(M, t):
    """Box caption."""
    if M.block(t)['scene'] != 'frame' or not M.format_landscape():
        return None
    (x0, _y0, x1, _y1) = M.F['frameArea']
    return (int(x0), int(x1 - x0))

def top_caption(M, a, b, hcap, last=None, box=None, width=None):
    F = M.F
    (lo, hi) = F['captions']
    r = M.face_screen(a)
    (cx0, cx1) = (box[0], box[0] + box[1]) if box else (40, M.W - 40)
    if width and (not box):
        (cx0, cx1) = (max(cx0, M.W / 2 - width / 2), min(cx1, M.W / 2 + width / 2))
    base = F['defaultCaptionY'] if not r else int(clamp(r['y1'] + F['captionPadding'], lo, hi))
    alternatives = list(F['alternateCaptions'])
    if M.block(a)['scene'] == 'frame':
        (mx, my, mw, mh) = M.FRAME
        (ax0, ay0, ax1, ay1) = F['frameArea']
        if box:
            (base, alternatives) = (int(ay1 - hcap - 10), [int(ay0 + 10)])
        else:
            (base, alternatives) = (int(my - hcap - 24), [int(ay0 + 10)])
    reason = []

    def hit(y):
        for (t0, t1, x, yy, w, h) in M.rectangles:
            if t0 < b and a < t1 and (y < yy + h + 10) and (yy < y + hcap + 10) and (x < cx1) and (cx0 < x + w):
                reason.append('inside an animation')
                return True
        if r is not None and y < r['y1'] and (r['y0'] < y + hcap) and (r['x0'] < cx1) and (cx0 < r['x1']):
            reason.append('on the face')
            return True
        return False
    prefer = [last] if last is not None and abs(last - base) < 40 else []
    for y in prefer + [base] + alternatives:
        if not hit(y):
            return int(y)
    where = 'inside an animation' if 'inside an animation' in reason else 'on the face'
    warn(f'captions at_time {a:.2f} s encosta {where}; moved to {base}px')
    return base

def measure_sound(path):
    """Measure sound."""
    cache_p = os.path.join(HERE, '.sound_cache.json')
    try:
        with open(cache_p, encoding='utf-8') as f:
            cache = json.load(f)
    except (OSError, ValueError):
        cache = {}
    st = os.stat(path)
    key = f'{path}|{st.st_size}|{int(st.st_mtime)}|v2'
    if key in cache:
        return tuple(cache[key])
    info = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'a:0', '-show_entries', 'stream=sample_rate,channels', '-of', 'csv=p=0', path], capture_output=True, text=True, encoding='utf-8', errors='replace').stdout.strip().split(',')
    try:
        (sr, ch) = (int(info[0]), int(info[1]))
    except (ValueError, IndexError):
        raise BuildError(f'could not read sound {path} (ffprobe could not parse the file)')
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-f', 's16le', '-acodec', 'pcm_s16le', '-'], capture_output=True).stdout
    a = array('h')
    a.frombytes(raw[:len(raw) // 2 * 2])
    if sys.byteorder == 'big':
        a.byteswap()
    (bi, bv) = (0, 1)
    step = max(1, int(sr * 0.005)) * ch
    env = []
    for k0 in range(0, len(a), step):
        m = 1
        for k in range(k0, min(len(a), k0 + step)):
            v = abs(a[k])
            if v > m:
                m = v
                if v > bv:
                    (bv, bi) = (v, k)
        env.append(m)
    res = (len(a) / ch / sr, bi // ch / sr, 20 * math.log10(bv / 32768), env)
    cache[key] = res
    with open(cache_p, 'w', encoding='utf-8') as f:
        json.dump(cache, f)
    return res

def peak_interval(env, a, b):
    """Peak interval."""
    (i0, i1) = (int(a / 0.005), max(int(a / 0.005) + 1, int(math.ceil(b / 0.005))))
    v = max(env[i0:i1] or [1])
    return 20 * math.log10(max(v, 1) / 32768)

def sounds(M):
    """Sounds."""
    list = M.P.cfg.get('sounds', [])
    end_video = M.P.VDUR + M.tail
    n = 0
    for (i, s) in enumerate(list):
        name = f"sound {i + 1} ({s.get('file', '?')})"
        if not s.get('file'):
            warn(f'Sound {i + 1}: missing file.')
            continue
        file = os.path.join(HERE, s['file'])
        if not os.path.exists(file):
            warn(f'{name}: file not found; omitted')
            continue
        try:
            peak = M.P.time(s, 'at')
        except BuildError as e:
            warn(f'{name}: {e}; omitted')
            continue
        if peak is None:
            warn(f'{name}: missing "at" (the cut second where the peak lands); omitted')
            continue
        (dur_file, measured_peak, _pdb, env) = measure_sound(file)
        tp = float(s['sourcePeak']) if s.get('sourcePeak') is not None else measured_peak
        off = float(s.get('sourceStart', 0) or 0)
        if peak < -0.001 or peak > end_video + 0.001:
            warn(f'{name}: peak occurs at {peak:.2f} s, outside the video (0 to {end_video:.2f} s); omitted')
            continue
        start_time = peak - (tp - off)
        fade_in = float(s.get('fadeIn', 0) or 0)
        play = float(s['dur']) if s.get('dur') is not None else float(s.get('max', 1.2))
        end_file = min(off + play, dur_file)
        if start_time < 0:
            (off, start_time) = (off - start_time, 0.0)
            fade_in = max(fade_in, 0.01)
        dur = end_file - off
        if dur <= 0.02:
            warn(f'{name}: "sourceStart" ({off:.3f} s) exceeds file duration ({dur_file:.3f} s); omitted')
            continue
        if start_time + dur <= M.T0 + 0.001 or start_time >= M.T0 + M.DUR - 0.001:
            continue
        if start_time < M.T0:
            (off, dur, start_time) = (off + (M.T0 - start_time), dur - (M.T0 - start_time), M.T0)
            fade_in = max(fade_in, 0.01)
        cut = start_time + dur > M.T0 + M.DUR
        dur = min(dur, M.T0 + M.DUR - start_time)
        if dur <= 0.02:
            continue
        if s.get('volume') is not None:
            vol = float(s['volume'])
        else:
            vol = 10 ** ((float(s.get('db', SOUND_SMALL)) - peak_interval(env, off, off + dur)) / 20)
        if vol > VOLUME_MAX:
            warn(f'{name}: requested volume {vol:.2f} exceeds +12 dB; capped at {VOLUME_MAX}. Choose a louder source.')
            vol = VOLUME_MAX
        fade = min(float(s.get('fade', 0) or 0), dur)
        if cut and fade < 0.03:
            fade = min(0.05, dur)
        extra = (f' data-fade-in="{round(min(fade_in, dur), 3)}"' if fade_in > 0 else '') + (f' data-fade-out="{round(fade, 3)}"' if fade > 0 else '')
        rot = s.get('type') or os.path.splitext(os.path.basename(s['file']))[0]
        if s.get('note'):
            rot = f"{rot} · {s['note']}"
        M.AUD.append(f'''<audio id="sound{i}" src="{escape(s['file'])}" data-start="{M.rr(start_time)}" data-duration="{round(dur, 3)}" data-media-start="{round(off, 4)}" data-volume="{round(vol, 3)}"{extra} data-track-index="{TRACK_SOUNDS + i}" data-timeline-label="Sound · {escape(str(rot))}"></audio>''')
        n += 1
    return n
