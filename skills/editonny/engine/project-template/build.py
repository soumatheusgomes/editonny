def comparison_side(b, key, suffix):
    s = b.get(key)
    name = f'''compare at_time {b['start']:.2f} s, side "{key}"'''
    if not isinstance(s, dict) or not s.get('file'):
        raise BuildError(f'{name}: provide file and label (file cut uses an interval from the cut itself).')
    rot = str(s.get('label') or '').strip()
    if not rot:
        raise BuildError(f'{name}: provide a factual label such as Original recording or Voice cleaned.')
    bad = [w for w in re.findall('\\w+', norm(rot.replace('*', ''))) if w in OPINION_WORDS]
    if bad:
        warn(f'''{name}: label "{rot}" contains opinion words ({', '.join(bad)}). Describe the side factually and let viewers judge.''')
