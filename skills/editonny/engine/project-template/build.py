RE_TEMPLATE = re.compile('<template\\b[^>]*>(.*)</template>', re.S | re.I)
RE_CID = re.compile('data-composition-id\\s*=\\s*["\\\']([^"\\\']+)["\\\']')

def read_scene(file):
    """Read scene."""
    path = os.path.join(HERE, file)
    if not os.path.exists(path):
        raise BuildError(f'Custom scene not found: {file}. Paths are relative to the project, for example compositions/scenes/budget.html.')
    with open(path, encoding='utf-8') as f:
        txt = f.read()
    m = RE_TEMPLATE.search(txt)
    if not m:
        raise BuildError(f'{file}: the scene must be inside <template> (see compositions/scenes/README.md)')
    m2 = RE_CID.search(m.group(1))
    if not m2:
        raise BuildError(f'{file}: missing data-composition-id on the scene root (see compositions/scenes/README.md)')
    cid = m2.group(1)
    if not re.search('__timelines\\s*\\[\\s*["\\\']' + re.escape(cid) + '["\\\']\\s*\\]\\s*=', m.group(1)):
        raise BuildError(f'{file}: register the timeline with the same name as the root: window.__timelines["{cid}"] = tl;')
    if cid == 'main' or cid.startswith('piece-'):
        raise BuildError(f'{file}: composition ID "{cid}" is reserved. Use the scene filename, such as budget.')
    return cid
RE_ROOT = re.compile('<[A-Za-z][\\w-]*\\b[^>]*\\bdata-composition-id\\s*=\\s*["\\\'][^"\\\']+["\\\'][^>]*>')
RE_SCRIPT = re.compile('<script\\b[^>]*>(.*?)</script\\s*>', re.S | re.I)

def scene_root(file):
    """Read root dimensions and detect responsive scenes."""
    with open(os.path.join(HERE, file), encoding='utf-8') as f:
        m = RE_TEMPLATE.search(f.read())
    body = m.group(1) if m else ''
    tag = RE_ROOT.search(body)

    def number(name):
        v = re.search('\\b' + name + '\\s*=\\s*["\\\']?\\s*(\\d+(?:\\.\\d+)?)', tag.group(0)) if tag else None
        return int(round(float(v.group(1)))) if v else None
    js = '\n'.join(RE_SCRIPT.findall(body))
    responsive = '__scenes' in js and ('scene-engine' in js or bool(re.search('\\bwidth\\b', js) and re.search('\\bheight\\b', js)))
    return (number('data-width'), number('data-height'), responsive)

def adjust_root(M, file, cid):
    """Adjust root."""
    (rw, rh, responsive) = scene_root(file)
    if rw is None or rh is None or (abs(rw - M.W) <= 1 and abs(rh - M.H) <= 1):
        return None
    if responsive:
        M.css(f'root-{cid}', f'#scene-{cid},#scene-{cid}>*{{width:{M.W}px!important;height:{M.H}px!important}}')
        return (rw, rh)
    warn(f'{file}: root is {rw}x{rh} while video is {M.W}x{M.H}. Use matching root dimensions and draw from window.__scenes width and height (compositions/scenes/README.md).')
    return None

def share_frame(a0, a1, b0, b1):
    """Share frame."""
    (start_time, end) = (max(a0, b0), min(a1, b1))
    k = math.ceil((start_time - 0.001) * FPS - 1e-09)
    return k / FPS < end - 0.001

def scene_frame(M, start_time, end):
    """Find the framed block overlapping a scene."""
    for b in M.blocks:
        if b['scene'] != 'frame':
            continue
        b0 = max(b['start'], b.get('_requestedStart', b['start']))
        b1 = min(b['end'], b.get('_requestedEnd', b['end']))
        if b1 > b0 and share_frame(start_time, end, b0, b1):
            return b
    return None

def scene_name(file):
    base = os.path.splitext(os.path.basename(file))[0]
    return 'Scene · ' + base.replace('_', ' ')

def scenes_custom(M):
    P = M.P
    (seen, n, adjusted) = ({}, 0, [])
    for (i, c) in enumerate(P.cfg.get('scenes', [])):
        file = c.get('file')
        if not file:
            raise BuildError(f'custom scene {i + 1}: missing "file" (for example: "compositions/scenes/budget.html")')
        cid = read_scene(file)
