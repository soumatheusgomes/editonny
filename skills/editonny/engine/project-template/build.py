def piece_in_hand(M, p, pid):
    """Attach an image to a smoothed hand track."""
    (t_in, t_out) = entry_exit(M, p, 3.0)
    file = os.path.join(HERE, p.get('hands', 'assets/hands.json'))
    if not os.path.exists(file):
        raise BuildError(f"{pid}: missing {p.get('hands', 'assets/hands.json')}. Run tools/track_hands.py first.")
    with open(file, encoding='utf-8') as f:
        D = json.load(f)
    which = p.get('hand', 'imageRight')
    size = float(p.get('size', 180 * M.F['scale']))
    padding = float(p.get('padding', 30))
    frames = {int(round(q['t'] * FPS)): q for q in D['frames']}
    (n0, n1) = (int(math.floor(t_in * FPS)), int(math.ceil(t_out * FPS)))
    (target, last) = ({}, None)
    for n in range(n0, n1 + 1):
        q = frames.get(n)
        hands = [m for m in (q or {}).get('hands', []) if which == 'qualquer' or m['side'] == which]
        if hands:
            m = hands[0]
            c = M.cam(n / FPS)
            (nx, ny) = M.vid(m['nodes'][0], m['nodes'][1])
            (sx, sy) = (c['x'] + c['scale'] * nx, c['y'] + c['scale'] * ny)
            last = (sx, sy - size / 2 - padding)
        target[n] = last
    if not any(target.values()):
        raise BuildError(f'{pid}: hand "{which}" is absent between {t_in:.2f} and {t_out:.2f} s.')
    first = next((v for v in target.values() if v))
    for n in target:
        target[n] = target[n] or first
    (wn, zeta, sub) = (2 * math.pi * 3.4, 0.45, 10)
    (pos, velocity) = (list(first), [0.0, 0.0])
    M.css('in-hand', '.in-hand{position:absolute;left:0;top:0;width:0;height:0}\n.in-hand .pop{position:absolute;opacity:0}\n.in-hand img{display:block;width:100%;height:100%;object-fit:contain;filter:drop-shadow(0 14px 22px rgba(0,0,0,.45))}')
    img = resize_image(p['image'], round(size), round(size), 'contain')
    M.HT.append(f'<div class="in-hand" id="{pid}"><div class="pop" id="{pid}-p" style="left:{-size / 2:.0f}px;top:{-size / 2:.0f}px;width:{size:.0f}px;height:{size:.0f}px"><img src="{escape(img)}" alt=""/></div></div>')
    pairs = []
    for n in range(n0, n1 + 1):
        tgt = target[n]
        for _ in range(sub):
            for d in (0, 1):
                acc = wn * wn * (tgt[d] - pos[d]) - 2 * zeta * wn * velocity[d]
                velocity[d] += acc / (FPS * sub)
                pos[d] += velocity[d] / (FPS * sub)
        rz = clamp(-velocity[0] * 0.006, -11, 11)
        pairs.append((n / FPS, {'x': round(pos[0], 1), 'y': round(pos[1], 1), 'rotation': round(rz, 2)}))
    M.FRAMES(f'#{pid}', pairs)
    M.FT(f'#{pid}-p', {'opacity': 0, 'y': 24, 'clipPath': 'circle(12% at 50% 50%)'}, {'opacity': 1, 'y': 0, 'clipPath': 'circle(100% at 50% 50%)', 'duration': 0.4, 'ease': 'back.out(2)'}, t_in)
    M.TO(f'#{pid}-p', {'opacity': 0, 'clipPath': 'circle(12% at 50% 50%)', 'duration': 0.18, 'ease': 'power2.in'}, t_out - 0.18)
    M.sound('pop', t_in + 0.08, SOUND_KEY, pid)
    M.sound('pop', t_out - 0.1, SOUND_SMALL, pid)

